// Reverse pass through the buffer to work out all the runs of repeated values
size_t rleCompress(const uint8_t* src, uint16_t srcLen, uint8_t* dst);
uint16_t rleDecompress(const uint8_t* src, uint16_t srclen, uint8_t* dst, uint16_t dstmax);

// Add a file to the disk 
void addFile(const std::wstring& filename, const char* diskFilename, AdfVolume* vol) {
    // open a file    
    
    struct AdfFile* const file = adfFileOpen(vol, diskFilename, ADF_FILE_MODE_WRITE);
    if (file == NULL) return;

    HANDLE fle = CreateFile(filename.c_str(), GENERIC_READ, 0, NULL, OPEN_EXISTING, 0, NULL);
    uint8_t buffer[512];
    DWORD tmp;
    assert(fle != INVALID_HANDLE_VALUE);

    do {
        ReadFile(fle, buffer, sizeof(buffer), &tmp, NULL);
        adfFileWrite(file, tmp, buffer);
    } while (tmp >= sizeof(buffer));
    CloseHandle(fle);

    // close the file
    adfFileClose(file);
}

// Prevent the special upper tracks being used
void markTracksUsed(struct AdfVolume* vol, int firstTrack, int lastTrack) {
    int track, side, sector;
    for (track = firstTrack; track <= lastTrack; track++) {
        for (side = 0; side < 2; side++) {
            for (sector = 0; sector < 11; sector++) {
                ADF_SECTNUM block = (track * 2 + side) * 11 + sector;
                adfSetBlockUsed(vol, block);
            }
        }
    }
}


